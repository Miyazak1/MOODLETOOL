export function normalizeLocale(value: string | null | undefined): PortalLocale | null {
  const normalized = String(value || "").trim().toLowerCase();
  if (!normalized) return null;
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  if (normalized === "zh" || normalized.startsWith("zh-")) return "zh-CN";
  return null;
}

export function detectInitialLocale(): PortalLocale {
  const params = new URLSearchParams(window.location.search);
  const urlLocale = normalizeLocale(params.get("lang"));
  if (urlLocale) return urlLocale;

  try {
    const storedLocale = normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
    if (storedLocale) return storedLocale;
  } catch {
    // Ignore storage access failures in restricted browser contexts.
  }

  const browserLocales = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const locale of browserLocales) {
    const detected = normalizeLocale(locale);
    if (detected) return detected;
  }

  return "en";
}

export function storeLocale(locale: PortalLocale): void {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Ignore storage access failures in restricted browser contexts.
  }
}

export function translate(locale: PortalLocale, key: string, params?: Record<string, string | number>): string {
  const value = messages[locale][key] ?? messages.en[key] ?? key;
  return typeof value === "function" ? value(params || {}) : value;
}
