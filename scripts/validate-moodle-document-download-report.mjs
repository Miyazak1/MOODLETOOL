import { existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const queuePath = join(projectRoot, "inbox", "moodle-course-document-queue.csv");
const reportPath = join(projectRoot, "deployment", "moodle-document-download-report.json");
const coursewareRoot = resolve(projectRoot, "..", "courseware");

function fail(message) {
  console.error(message);
  process.exit(1);
}

function parseCsvLine(line) {
  const cells = [];
  let cell = "";
  let quoted = false;

  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        cell += '"';
        i += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        cell += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      cells.push(cell);
      cell = "";
    } else {
      cell += char;
    }
  }
  cells.push(cell);
  return cells;
}

function readCsv(path) {
  if (!existsSync(path)) fail(`Missing CSV: ${path}`);
  const lines = readFileSync(path, "utf8").split(/\r?\n/).filter(Boolean);
  if (!lines.length) return [];
  const headers = parseCsvLine(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = parseCsvLine(line);
    return Object.fromEntries(headers.map((header, index) => [header, cells[index] ?? ""]));
  });
}

function readJson(path) {
  if (!existsSync(path)) fail(`Missing JSON: ${path}`);
  return JSON.parse(readFileSync(path, "utf8"));
}

function hasLocalCourseOutline(course) {
  const manifestPath = join(coursewareRoot, course, "course-manifest.json");
  if (!existsSync(manifestPath)) return false;
  const manifest = readJson(manifestPath);
  return (manifest.courseDownloads || []).some((item) => item.role === "course_outline" && item.path);
}

const queueRows = readCsv(queuePath);
const readyRows = queueRows.filter((row) => row.status === "ready" && row.url);
const readyByCourse = new Map(readyRows.map((row) => [row.course, row]));
const report = readJson(reportPath);
const reportRows = report.rows || [];
const reportByCourse = new Map(reportRows.map((row) => [row.course, row]));
const errors = [];

if (report.dryRun !== true) errors.push("Download report must be generated by plan:moodle-doc-queue dry-run.");
if (report.force !== false) errors.push("Download report validation expects force=false.");
if (typeof report.moodleCookieConfigured !== "boolean") errors.push("Download report is missing moodleCookieConfigured boolean.");
if (reportRows.length !== readyRows.length) errors.push(`Report rows (${reportRows.length}) do not match ready queue rows (${readyRows.length}).`);

for (const row of readyRows) {
  const reportRow = reportByCourse.get(row.course);
  if (!reportRow) {
    errors.push(`${row.course} is ready in queue but missing from download report.`);
    continue;
  }
  if (reportRow.role !== row.role) errors.push(`${row.course} report role does not match queue role.`);
  if (reportRow.url !== row.url) errors.push(`${row.course} report URL does not match queue URL.`);
  if (!String(reportRow.targetPath || "").endsWith(`courseware\\${row.course}\\plans\\course\\${row.targetFilename}`)) {
    errors.push(`${row.course} targetPath does not point to the expected courseware plans/course file.`);
  }

  const localOutline = hasLocalCourseOutline(row.course);
  if (localOutline && reportRow.status !== "skipped") {
    errors.push(`${row.course} has a local course outline and should be skipped in dry-run.`);
  }
  if (!localOutline && reportRow.status !== "would-download") {
    errors.push(`${row.course} has no local course outline and should be marked would-download in dry-run.`);
  }
  if (reportRow.status === "would-download" && !["missing", "remote", "unknown"].includes(reportRow.manifestOutlineMode)) {
    errors.push(`${row.course} would-download has unexpected manifestOutlineMode: ${reportRow.manifestOutlineMode}`);
  }
}

for (const row of reportRows) {
  if (!readyByCourse.has(row.course)) errors.push(`${row.course} appears in report but is not ready in queue.`);
  if (!["would-download", "skipped"].includes(row.status)) errors.push(`${row.course} has unexpected dry-run status: ${row.status}`);
}

if (errors.length) {
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}

const wouldDownload = reportRows.filter((row) => row.status === "would-download").length;
const skipped = reportRows.filter((row) => row.status === "skipped").length;
console.log(`Moodle document download report OK: ${reportRows.length} ready rows; ${wouldDownload} would download; ${skipped} skipped.`);
